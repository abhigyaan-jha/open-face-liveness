// Writes src/models/bundled-assets.generated.ts from models/manifest.json.
// Every asset is referenced as `new URL('<literal path>', import.meta.url)`, the pattern
// Vite, webpack 5, Rspack, Parcel, and Next.js detect to emit the file with the app's build.
// Run after changing models/ or vendor/tfjs-wasm/; package:audit fails if the output is stale.
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

export const TFJS_WASM_FILES = [
  'tfjs-backend-wasm.wasm',
  'tfjs-backend-wasm-simd.wasm',
  'tfjs-backend-wasm-threaded-simd.wasm',
];

export const OUTPUT_PATH = 'src/models/bundled-assets.generated.ts';

// src/models/ and dist/models/ sit at the same depth, so one relative path works for both.
const toModuleUrl = (packagePath) =>
  `new URL(${JSON.stringify(path.posix.relative(path.posix.dirname(OUTPUT_PATH), packagePath))}, import.meta.url).href`;

export const generateBundledAssets = (root = process.cwd()) => {
  const manifest = JSON.parse(fs.readFileSync(path.join(root, 'models/manifest.json'), 'utf8'));

  const modelFileLines = manifest.models.flatMap((model) => {
    const modelDirectory = path.posix.dirname(model.url);
    return Object.keys(model.files).sort().map((file) => {
      const manifestPath = path.posix.join(modelDirectory, file);
      return `  ${JSON.stringify(manifestPath)}: ${toModuleUrl(path.posix.join('models', manifestPath))},`;
    });
  });

  const wasmFileLines = TFJS_WASM_FILES.map(
    (file) => `  ${JSON.stringify(file)}: ${toModuleUrl(path.posix.join('vendor/tfjs-wasm', file))},`,
  );

  return `// Generated by scripts/generate-bundled-assets.mjs from models/manifest.json. Do not edit.
import type { ModelManifest } from '../models.js';

export const BUNDLED_MODEL_MANIFEST: ModelManifest = ${JSON.stringify(manifest, null, 2)};

// Keyed by path relative to models/. The literal paths let bundlers find and emit each file.
export const getBundledModelFileUrls = (): Record<string, string> => ({
${modelFileLines.join('\n')}
});

export const getBundledTfjsWasmUrls = (): Record<string, string> => ({
${wasmFileLines.join('\n')}
});
`;
};

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(process.cwd(), OUTPUT_PATH), generateBundledAssets());
  console.log(`Wrote ${OUTPUT_PATH}.`);
}
